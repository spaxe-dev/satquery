def load_bigearthnet_instruct(json_path: str, hub_root: str = "datasets/raw/bigearthnet/bigearthnet-mini") -> Tuple[List[Dict], List[Dict]]:
    """
    Load BigEarthNet instruction JSON (generated by download_bigearthnet.py)
    Verify that referenced Hub indices exist.
    """
    p = Path(json_path)
    if not p.exists():
        raise FileNotFoundError(f"BigEarthNet instruct JSON not found: {json_path}")
    with open(p) as f:
        data = json.load(f)
    print(f"Loaded {len(data)} BigEarthNet instruction entries from {json_path}")

    # Verify a few entries reference valid Hub indices
    import deeplake
    hub_root = Path(hub_root)
    # Try to find train hub
    train_hub = hub_root / "train" if (hub_root / "train").exists() else hub_root
    if not train_hub.exists():
        # Try alternative: hub_root is already train
        train_hub = hub_root
    try:
        ds = deeplake.load(str(train_hub)) if (train_hub / "data").exists() else deeplake.load(str(hub_root / "train"))
        n = len(ds)
        print(f"Hub {train_hub} len {n}")
        for entry in data[:3]:
            idx = entry.get("patch_idx", 0)
            if idx >= n and entry["split"] == "train":
                print(f"Warning: patch_idx {idx} >= train len {n}")
            # Check labels are real
            assert "labels" in entry and len(entry["labels"]) > 0
    except Exception as e:
        print(f"Hub verification warning: {e}")

    train = [d for d in data if d.get("split") == "train"]
    val = [d for d in data if d.get("split") == "val"]
    if not train or not val:
        import random
        random.seed(42)
        random.shuffle(data)
        n_train = int(len(data)*0.8)
        train = data[:n_train]
        val = data[n_train:]
        for e in train: e["split"]="train"
        for e in val: e["split"]="val"

    print(f"BigEarthNet train: {len(train)}, val: {len(val)}")
    # Check label distribution
    from collections import Counter
    all_labels = []
    for e in data:
        all_labels.extend(e.get("labels", []))
    cnt = Counter(all_labels)
    print(f"Label distribution top 5: {cnt.most_common(5)}")

    return train, val

class BigEarthNetHubDataset(torch.utils.data.Dataset if _TORCH_AVAILABLE else object):
    """
    PyTorch Dataset that loads REAL BigEarthNet patches from Hub via deeplake
    and provides instruction tuning samples for BLIP/Qwen2-VL.

    Each entry in instruct JSON corresponds to a Hub index; we load the (3,120,120) BGR patch
    and convert to PIL RGB for the processor.
    """
    def __init__(self, entries: List[Dict], hub_root: str, processor, processor_type: str = "blip", max_length: int = 128):
        self.entries = entries
        self.hub_root = Path(hub_root)
        self.processor = processor
        self.processor_type = processor_type
        self.max_length = max_length
        # Open Hub datasets (lazy)
        import deeplake
        # Check if hub_root is a Hub dataset or parent containing train/val
        if (self.hub_root / "train" / "data").exists():
            self.hub_train = deeplake.load(str(self.hub_root / "train"))
            self.hub_val = deeplake.load(str(self.hub_root / "val"))
        elif (self.hub_root / "data").exists():
            # hub_root is already a split
            self.hub_train = self.hub_val = deeplake.load(str(self.hub_root))
        else:
            # Fallback: try to load as is
            self.hub_train = deeplake.load(str(self.hub_root))
            self.hub_val = self.hub_train

        print(f"BigEarthNetHubDataset: {len(self.entries)} entries, hub train len {len(self.hub_train)}, val len {len(self.hub_val)}")

    def __len__(self):
        return len(self.entries)

    def _load_image(self, entry):
        # Load from Hub via patch_idx and split
        split = entry.get("split", "train")
        idx = entry.get("patch_idx", 0)
        hub = self.hub_train if split == "train" else self.hub_val
        # Clamp idx
        idx = idx % len(hub)
        sample = hub[idx]
        data = sample["data"].numpy()  # (3,120,120) BGR, likely uint8 or float?
        # Data in Hub is stored as BGR? The jerpint code says BGR. Convert to RGB.
        # data shape (3,120,120), values maybe 0-255?
        # Check dtype
        if data.dtype != np.uint8:
            # If float, scale?
            # The Hub data is likely uint8 0-255, but stored as lz4 compressed
            # If float, assume 0-255 range
            data = np.clip(data, 0, 255).astype(np.uint8)
        # Convert BGR to RGB
        # Hub stores as BGR (as per target_bands BGR), so reverse
        # data[0] is B, data[1] is G, data[2] is R -> convert to RGB = [2,1,0]
        data_rgb = data[::-1, :, :]  # BGR -> RGB
        # Convert to HWC PIL
        img = np.transpose(data_rgb, (1,2,0))  # (120,120,3)
        pil = Image.fromarray(img.astype(np.uint8))
        return pil

    def __getitem__(self, idx):
        entry = self.entries[idx]
        image = self._load_image(entry)
        query = entry["query"]
        answer = entry["answer"]

        if self.processor_type == "blip":
            encoding = self.processor(images=image, text=answer, return_tensors="pt", padding="max_length", truncation=True, max_length=self.max_length)
            item = {k: v.squeeze(0) for k, v in encoding.items()}
            item["labels"] = item["input_ids"]
            item["query"] = query
            item["answer"] = answer
            return item
        elif self.processor_type == "qwen2_vl":
            messages = [
                {"role": "user", "content": [{"type": "image"}, {"type": "text", "text": query}]},
                {"role": "assistant", "content": [{"type": "text", "text": answer}]}
            ]
            try:
                text = self.processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)
                inputs = self.processor(text=[text], images=[image], return_tensors="pt", padding="max_length", max_length=self.max_length, truncation=True)
                item = {k: v.squeeze(0) for k, v in inputs.items()}
                item["labels"] = item["input_ids"].clone()
                return item
            except Exception:
                encoding = self.processor(text=query + " " + answer, images=image, return_tensors="pt", padding=True, truncation=True)
                item = {k: v.squeeze(0) for k, v in encoding.items()}
                item["labels"] = item["input_ids"]
                return item
        else:
            raise ValueError(f"Unknown processor_type {self.processor_type}")

def verify_bigearthnet_real(json_path: str, hub_root: str, num_samples: int = 3):
    """Verify real BigEarthNet Hub images can be loaded and have correct shape/labels."""
    train, val = load_bigearthnet_instruct(json_path, hub_root)
    print(f"Verifying {num_samples} BigEarthNet samples...")
    import deeplake
    hub_root = Path(hub_root)
    # Test via HubDataset class with dummy processor
    # Instead, directly test via Hub
    ds_train = deeplake.load(str(hub_root / "train")) if (hub_root / "train").exists() else deeplake.load(str(hub_root))
    for i in range(min(num_samples, len(train))):
        entry = train[i]
        idx = entry["patch_idx"]
        sample = ds_train[idx % len(ds_train)]
        data = sample["data"].numpy()
        labels = sample["labels"].numpy()
        print(f"  train[{i}] patch_idx {idx} data {data.shape} dtype {data.dtype} labels {labels.flatten().tolist()[:3]} -> {entry['labels'][:2]}")
        assert data.shape == (3,120,120), f"Unexpected shape {data.shape}"
        assert len(entry["labels"]) > 0
    print("BigEarthNet real verification passed.")
    return True
