"""
Real RS dataset loader — EuroSAT (and BigEarthNet mini fallback)
Loads instruction JSON generated by scripts/download_eurosat.py and verifies files.
"""
import json, os, pathlib
from pathlib import Path
from typing import List, Dict, Tuple
from PIL import Image

# EuroSAT class names for verification
EUROSAT_CLASSES = ["AnnualCrop","Forest","HerbaceousVegetation","Highway","Industrial","Pasture","PermanentCrop","Residential","River","SeaLake"]

def load_eurosat_instruct(json_path: str, raw_root: str = "datasets/raw/eurosat") -> Tuple[List[Dict], List[Dict]]:
    """
    Load EuroSAT instruction JSON, verify images exist, return train/val splits.
    JSON structure: list of {image, query, answer, label, label_id, split, source}
    image path is relative to raw_root or project root.
    """
    p = Path(json_path)
    if not p.exists():
        raise FileNotFoundError(f"Instruction JSON not found: {json_path}")
    with open(p, "r") as f:
        data = json.load(f)
    print(f"Loaded {len(data)} instruction entries from {json_path}")

    # Verify files exist
    raw_root_path = Path(raw_root)
    missing = 0
    for entry in data:
        img_path = entry["image"]
        # Try multiple resolutions
        candidates = [
            raw_root_path / img_path,
            Path(img_path),
            Path("datasets/raw/eurosat") / img_path,
            Path(img_path.replace("datasets/raw/eurosat/", "")) if "datasets/raw/eurosat" in img_path else None,
        ]
        found = any(c and c.exists() for c in candidates if c)
        if not found:
            # Try relative to project root
            alt = Path(img_path)
            if not alt.exists():
                missing += 1
                if missing <= 3:
                    print(f"Missing image: {img_path}")
        # Check that answer is non-empty and derived from real label
        if not entry.get("answer"):
            print(f"Empty answer for {entry}")

    if missing > 0:
        print(f"WARNING: {missing}/{len(data)} images missing (may be synthetic placeholder)")
        if missing > len(data) * 0.5:
            raise FileNotFoundError(f"Too many missing images {missing}/{len(data)} — dataset not downloaded correctly")

    # Split
    train = [d for d in data if d.get("split") == "train"]
    val = [d for d in data if d.get("split") == "val"]
    # If no split field, do 85/15 random
    if not train or not val:
        import random
        random.seed(42)
        random.shuffle(data)
        n_train = int(len(data)*0.85)
        train = data[:n_train]
        val = data[n_train:]
        for e in train: e["split"]="train"
        for e in val: e["split"]="val"

    print(f"Train: {len(train)}, Val: {len(val)}")
    # Check class distribution
    from collections import Counter
    train_dist = Counter([e.get("label") for e in train])
    val_dist = Counter([e.get("label") for e in val])
    print(f"Train dist: {dict(train_dist)}")
    print(f"Val dist: {dict(val_dist)}")

    # Verify that labels are real EuroSAT classes
    for e in data[:3]:
        assert e["label"] in EUROSAT_CLASSES, f"Invalid label {e['label']}"

    return train, val

class EuroSATInstructDataset:
    """PyTorch Dataset for instruction tuning — works with BLIP and Qwen2-VL processors."""
    def __init__(self, entries: List[Dict], raw_root: str, processor, processor_type: str = "blip", max_length: int = 128):
        self.entries = entries
        self.raw_root = Path(raw_root)
        self.processor = processor
        self.processor_type = processor_type  # "blip" or "qwen2_vl"
        self.max_length = max_length

    def __len__(self):
        return len(self.entries)

    def __getitem__(self, idx):
        entry = self.entries[idx]
        img_path = entry["image"]
        # Resolve image path
        candidates = [
            self.raw_root / img_path,
            Path(img_path),
            Path("datasets/raw/eurosat") / img_path,
        ]
        # Also handle if img_path is already relative like "EuroSAT/Forest/xxx.jpg"
        # Try each
        found_path = None
        for c in candidates:
            if c.exists():
                found_path = c
                break
        if found_path is None:
            # Try with raw_root / EuroSAT / ...
            for c in candidates:
                if c and (self.raw_root / "EuroSAT" / Path(img_path).name).exists():
                    found_path = self.raw_root / "EuroSAT" / Path(img_path).name
                    break
        if found_path is None:
            raise FileNotFoundError(f"Image not found for entry {idx}: {img_path} (tried {candidates})")

        image = Image.open(found_path).convert("RGB")
        query = entry["query"]
        answer = entry["answer"]

        # For BLIP: we train captioning — target is answer (caption)
        # For Qwen2-VL: we train instruction — prompt = query, target = answer
        if self.processor_type == "blip":
            # BLIP processor expects image and text
            # Use answer as caption; query is ignored for loss but can be prepended
            # We will tokenize answer as labels
            encoding = self.processor(images=image, text=answer, return_tensors="pt", padding="max_length", truncation=True, max_length=self.max_length)
            # Squeeze batch dim
            item = {k: v.squeeze(0) for k, v in encoding.items()}
            # For BLIP, labels are input_ids of text
            item["labels"] = item["input_ids"]
            # Also keep query for logging
            item["query"] = query
            item["answer"] = answer
            return item
        elif self.processor_type == "qwen2_vl":
            # Qwen2-VL processor: messages format
            # Simplified: processor(text=[query], images=[image])
            # For training, we need to create input_ids that include query and answer
            # Use chat template
            messages = [
                {"role": "user", "content": [{"type": "image"}, {"type": "text", "text": query}]},
                {"role": "assistant", "content": [{"type": "text", "text": answer}]}
            ]
            # Qwen2VL processor has apply_chat_template
            try:
                text = self.processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=False)
                inputs = self.processor(text=[text], images=[image], return_tensors="pt", padding="max_length", max_length=self.max_length, truncation=True)
                item = {k: v.squeeze(0) for k, v in inputs.items()}
                # Labels: mask user part, only train on assistant answer
                # Simplified: use input_ids as labels with -100 for prompt
                # For now, use full input_ids as labels (will be refined)
                item["labels"] = item["input_ids"].clone()
                return item
            except Exception as e:
                # Fallback to simple
                encoding = self.processor(text=query + " " + answer, images=image, return_tensors="pt", padding=True, truncation=True)
                item = {k: v.squeeze(0) for k, v in encoding.items()}
                item["labels"] = item["input_ids"]
                return item
        else:
            raise ValueError(f"Unknown processor_type {self.processor_type}")

def verify_real_dataset(json_path: str, raw_root: str, num_samples: int = 5):
    """Verify real dataset files open successfully."""
    train, val = load_eurosat_instruct(json_path, raw_root)
    print(f"Verifying {num_samples} samples...")
    # Try to open images
    for split, entries in [("train", train), ("val", val)]:
        for i, entry in enumerate(entries[:num_samples]):
            img_path = entry["image"]
            candidates = [Path(raw_root) / img_path, Path(img_path)]
            found = next((c for c in candidates if c.exists()), None)
            if found:
                try:
                    img = Image.open(found)
                    img.verify()
                    # Reopen for actual load
                    img = Image.open(found).convert("RGB")
                    assert img.size[0] >= 64 and img.size[1] >= 64
                    print(f"  {split}[{i}] OK: {found} {img.size} label={entry['label']}")
                except Exception as e:
                    print(f"  {split}[{i}] FAIL: {found} -> {e}")
                    raise
            else:
                print(f"  {split}[{i}] MISSING: {img_path}")
                raise FileNotFoundError(f"Missing {img_path}")
    print("Real dataset verification passed.")
    return True
