"""Generate PDF report from JSON report."""
import json, os, sys
from pathlib import Path

def generate_pdf(report_id):
    src = Path(f"reports/report_{report_id}.json")
    if not src.exists():
        print(f"Report not found: {src}")
        sys.exit(1)
    with open(src) as f:
        data = json.load(f)
    # Try reportlab
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.units import mm
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image as RLImage
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.lib import colors
        import io, base64
        from PIL import Image
    except ImportError:
        print("reportlab not installed. pip install reportlab")
        sys.exit(1)

    out = Path(f"reports/report_{report_id}.pdf")
    doc = SimpleDocTemplate(str(out), pagesize=A4, topMargin=15*mm, bottomMargin=15*mm, leftMargin=14*mm, rightMargin=14*mm)
    styles = getSampleStyleSheet()
    title = styles['Title']
    h1 = styles['Heading1']
    h2 = styles['Heading2']
    normal = styles['Normal']
    mono = styles['Code']

    story = []
    story.append(Paragraph("SatQuery AI — Analysis Report", title))
    story.append(Spacer(1, 4*mm))
    story.append(Paragraph(f"Report ID: {report_id} &nbsp;&nbsp; Task: {data.get('task')} &nbsp;&nbsp; {data.get('timestamp')}", normal))
    story.append(Spacer(1, 3*mm))

    story.append(Paragraph("Query", h2))
    story.append(Paragraph(data.get('query',''), normal))
    story.append(Spacer(1, 3*mm))

    story.append(Paragraph("Answer", h2))
    story.append(Paragraph(data.get('answer','').replace('\n','<br/>'), normal))
    story.append(Spacer(1, 3*mm))

    if data.get('caption'):
        story.append(Paragraph("Caption", h2))
        story.append(Paragraph(data.get('caption'), normal))
        story.append(Spacer(1, 3*mm))

    # Confidence table
    conf = data.get('confidence', {})
    story.append(Paragraph("Confidence (heuristic)", h2))
    rows = [["Metric","Score"]]
    for k in ["input_quality","model_confidence","evidence_agreement","cross_modal_support","overall"]:
        if k in conf and conf[k] is not None:
            rows.append([k, f"{conf[k]:.2f}"])
    rows.append(["is_heuristic", str(conf.get('is_heuristic', True))])
    t = Table(rows, colWidths=[80*mm, 30*mm])
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0), colors.HexColor('#111827')),('TEXTCOLOR',(0,0),(-1,0), colors.white),('ALIGN',(0,0),(-1,-1),'LEFT'),('GRID',(0,0),(-1,-1),0.5, colors.grey),('FONTSIZE',(0,0),(-1,-1),8),('BOTTOMPADDING',(0,0),(-1,-1),4)]))
    story.append(t)
    story.append(Spacer(1, 3*mm))

    # Tools
    story.append(Paragraph("Tools Used", h2))
    for tool in data.get('tools_used', []):
        story.append(Paragraph(f"• <b>{tool.get('tool_id')}</b> — {tool.get('reason')} &nbsp; params={tool.get('params')}", normal))
    story.append(Spacer(1, 3*mm))

    # Execution trace
    story.append(Paragraph("Execution Trace (auditable)", h2))
    for step in data.get('execution_trace', []):
        story.append(Paragraph(f"[{step.get('step'):02d}] {step.get('action')} — {step.get('detail')} <font color='grey'>({step.get('status')})</font> {step.get('tool') or ''}", mono))
    story.append(Spacer(1, 3*mm))

    # Visual evidence — embed previews if present
    if data.get('previews'):
        story.append(Paragraph("Visual Evidence", h2))
        for prev in data['previews']:
            # decode b64 to temp image
            try:
                b64 = prev.get('preview_b64')
                if b64:
                    img_data = base64.b64decode(b64)
                    tmp = Path(f"reports/_tmp_{report_id}_{prev['filename']}.png")
                    with open(tmp, "wb") as f:
                        f.write(img_data)
                    story.append(Paragraph(f"Image: {prev['filename']} — {prev['meta']['width']}x{prev['meta']['height']} — {prev['meta']['modality']}", normal))
                    story.append(RLImage(str(tmp), width=80*mm, height=80*mm))
                    story.append(Spacer(1, 2*mm))
            except Exception as e:
                story.append(Paragraph(f"Image {prev['filename']} preview error: {e}", normal))

    story.append(Paragraph("Validation", h2))
    story.append(Paragraph(json.dumps(data.get('validation', {}), indent=2).replace('\n','<br/>'), mono))
    story.append(Spacer(1, 4*mm))
    story.append(Paragraph("Generated by SatQuery AI v0.3.0 — SIH26167 — Heuristic confidence labeled as such. See docs/MODEL_CARD.md for model details.", normal))

    doc.build(story)
    print(f"PDF saved to {out}")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        # Use latest report
        import glob
        files = sorted(Path("reports").glob("report_*.json"), key=lambda x: x.stat().st_mtime, reverse=True)
        if not files:
            print("No reports found. Run an analysis first.")
            sys.exit(1)
        rid = files[0].stem.replace("report_","")
        print(f"Using latest report: {rid}")
        generate_pdf(rid)
    else:
        generate_pdf(sys.argv[1])
